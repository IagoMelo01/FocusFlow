type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
  label: (group: keyof typeof enumLabels.en, value: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(storageKey);
    if (stored === "en" || stored === "pt") {
      setLanguageState(stored);
    }
  }, []);

  const value = useMemo<I18nContextValue>(() => {
    function setLanguage(nextLanguage: Language) {
      setLanguageState(nextLanguage);
      window.localStorage.setItem(storageKey, nextLanguage);
      document.documentElement.lang = nextLanguage === "en" ? "en" : "pt-BR";
    }

    function t(key: string) {
      return translations[language][key as keyof typeof translations.en] ?? translations.en[key as keyof typeof translations.en] ?? key;
    }

    function label(group: keyof typeof enumLabels.en, itemValue: string) {
      const labels = enumLabels[language][group] as Record<string, string>;
      return labels[itemValue] ?? itemValue;
    }

    return { language, setLanguage, t, label };
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language === "en" ? "en" : "pt-BR";
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return context;
}
